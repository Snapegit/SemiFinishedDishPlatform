    >
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="投票名称" prop="toupiaomingcheng">
            <el-input v-model="ruleForm.toupiaomingcheng" 
                placeholder="投票名称" clearable :disabled=" false  ||ro.toupiaomingcheng"></el-input>
          </el-form-item>
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="投票图片" v-if="type!='cross' || (type=='cross' && !ro.toupiaotupian)" prop="toupiaotupian">
            <file-upload
            tip="点击上传投票图片"
            action="file/upload"
            :limit="3"
            :multiple="true"
            :fileUrls="ruleForm.toupiaotupian?ruleForm.toupiaotupian:''"
            @change="toupiaotupianUploadChange"
            ></file-upload>
          </el-form-item>
            <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' class="upload" v-else label="投票图片" prop="toupiaotupian">
                <img v-if="ruleForm.toupiaotupian.substring(0,4)=='http'" class="upload-img" style="margin-right:20px;" v-bind:key="index" :src="ruleForm.toupiaotupian.split(',')[0]" width="100" height="100">
                <img v-else class="upload-img" style="margin-right:20px;" v-bind:key="index" v-for="(item,index) in ruleForm.toupiaotupian.split(',')" :src="baseUrl+item" width="100" height="100">
            </el-form-item>
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="所得票数" prop="suodepiaoshu">
            <el-input v-model.number="ruleForm.suodepiaoshu" 
                placeholder="所得票数" clearable :disabled="true  ||ro.suodepiaoshu"></el-input>
          </el-form-item>
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="发布时间" prop="fabushijian">
              <el-date-picker
				  :disabled="true  ||ro.fabushijian"
                  value-format="yyyy-MM-dd HH:mm:ss"
                  v-model="ruleForm.fabushijian" 
                  type="datetime"
                  placeholder="发布时间">
              </el-date-picker>
          </el-form-item>
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="倒计结束时间" prop="reversetime">
              <el-date-picker
				  :disabled=" false  ||ro.reversetime"
                  value-format="yyyy-MM-dd HH:mm:ss"
                  v-model="ruleForm.reversetime" 
                  type="datetime"
                  placeholder="倒计结束时间">
              </el-date-picker>
          </el-form-item>
          <el-form-item :style='{"width":"100%","padding":"0px","margin":"0 0 20px","background":"none","display":"inline-block"}' label="投票内容" prop="toupiaoneirong">
            <el-input
              type="textarea"
              :rows="8"
              placeholder="投票内容"
              v-model="ruleForm.toupiaoneirong">
            </el-input>
          </el-form-item>

      <el-form-item :style='{"width":"100%","padding":"0","margin":"20px 0 0","textAlign":"center"}'>
        <el-button :style='{"border":"0px solid #eccc19","cursor":"pointer","padding":"0","margin":"0 20px 0 0","color":"#fff","borderRadius":"4px","background":"#C20C0C","width":"100px","lineHeight":"34px","fontSize":"14px","height":"34px"}'  type="primary" @click="onSubmit">提交</el-button>
        <el-button :style='{"border":"1px solid #ccc","cursor":"pointer","padding":"0","margin":"0","color":"#666","borderRadius":"4px","background":"none","width":"100px","lineHeight":"34px","fontSize":"14px","height":"34px"}' @click="back()">返回</el-button>
